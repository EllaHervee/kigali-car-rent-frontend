function exportLocalData() {
  var payload = {
    exportedAt: new Date().toISOString(),
    storage: "Kigali Car Rent server",
    accounts: REMOTE_USERS.map(function (user) {
      return {
        name: user.name,
        phone: user.phone,
        joinedAt: user.joinedAt,
      };
    }),
    authEvents: REMOTE_AUTH_LOGS.map(function (event) {
      return {
        action: event.action,
        phone: event.phone || null,
        occurredAt: event.ts,
      };
    }),
    payments: REMOTE_PAYMENTS.map(function (payment) {
      return {
        reference: payment.id,
        name: payment.name,
        provider: payment.provider,
        phone: payment.phone,
        amount: payment.amount,
        currency: payment.currency,
        status: payment.status,
        createdAt: payment.createdAt,
        confirmedAt: payment.confirmedAt,
      };
    }),
    bookings: REMOTE_BOOKINGS.concat(BK),
    fleet: REMOTE_CARS,
  };
  var blob = new Blob([JSON.stringify(payload, null, 2)], {
      type: "application/json",
    }),
    url = URL.createObjectURL(blob),
    link = document.createElement("a");
  link.href = url;
  link.download = "kigali-car-rent-backup-" + Date.now() + ".json";
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(function () {
    URL.revokeObjectURL(url);
  }, 1000);
  toast("Database backup downloaded.");
}

